export type Lang = "en" | "hi";

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  const raw = (lang === "hi" ? hi[key] : en[key]) ?? en[key];
  let value = Array.isArray(raw) ? raw.join(" · ") : String(raw);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}

export function translateList(lang: Lang, key: I18nKey): readonly string[] {
  const raw = (lang === "hi" ? hi[key] : en[key]) ?? en[key];
  return Array.isArray(raw) ? raw : [String(raw)];
}

export function monthName(lang: Lang, month: number, short = false): string {
  const list = short ? (lang === "hi" ? hi.monthNamesShort : en.monthNamesShort) : lang === "hi" ? hi.monthNames : en.monthNames;
  return list[month - 1] ?? "";
}

